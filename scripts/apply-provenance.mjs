#!/usr/bin/env node
// Derive the provenance-instrumented parser from pristine N3.js sources.
//
// The term-span instrumentation (see the term-provenance branch's commit
// message) is a formulaic transformation: a fixed set of context-anchored
// replacements in N3Lexer.js, N3Parser.js and index.js, plus one new file
// (N3ProvenanceParser.js).  This script applies it to an UNPATCHED N3.js
// source tree, so the instrumentation can be maintained out-of-tree and
// regenerated against upstream releases:
//
//   node scripts/apply-provenance.mjs <pristine-n3-src-dir> [<out-dir>]
//
// Every anchor must match its file exactly once; if upstream drifts, the
// script fails loudly naming the stale anchor (fix the payload, rerun the
// parity tests).  scripts/provenance-payload.json is generated by diffing
// this branch against main, so branch == main + this script, by
// construction — verify with:
//
//   node scripts/apply-provenance.mjs path/to/main/src /tmp/derived
//   diff -r /tmp/derived path/to/term-provenance/src
import Fs from 'fs';
import Path from 'path';
import { fileURLToPath } from 'url';

const here = Path.dirname(fileURLToPath(import.meta.url));
const payload = JSON.parse(Fs.readFileSync(Path.join(here, 'provenance-payload.json'), 'utf8'));

const srcDir = process.argv[2];
if (!srcDir) {
  console.error('usage: apply-provenance.mjs <pristine-n3-src-dir> [<out-dir>]');
  process.exit(1);
}
const outDir = process.argv[3] || srcDir;
Fs.mkdirSync(outDir, { recursive: true });

let applied = 0;
for (const [file, pairs] of Object.entries(payload.transforms)) {
  const base = Path.basename(file);
  let text = Fs.readFileSync(Path.join(srcDir, base), 'utf8');
  pairs.forEach((pair, i) => {
    const n = text.split(pair.old).length - 1;
    if (n !== 1) {
      console.error(`ANCHOR DRIFT in ${base} (transform ${i}: ${n} matches):\n---\n${pair.old}\n---`);
      process.exit(2);
    }
    text = text.replace(pair.old, pair.new);
    applied++;
  });
  Fs.writeFileSync(Path.join(outDir, base), text);
}
for (const [file, content] of Object.entries(payload.newFiles)) {
  Fs.writeFileSync(Path.join(outDir, Path.basename(file)), content);
  applied++;
}
console.log(`applied ${applied} transforms into ${outDir}`);
